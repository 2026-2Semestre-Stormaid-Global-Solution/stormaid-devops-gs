CREATE TABLE TB_STORMAID_RESCUE_UNIT_GS (
    RESCUE_UNIT_ID       NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    UNIT_CODE            VARCHAR2(30 CHAR)  NOT NULL,
    DISPLAY_NAME         VARCHAR2(120 CHAR) NOT NULL,
    INSTITUTION_TYPE     VARCHAR2(40 CHAR)  NOT NULL,
    CAPACITY             NUMBER(5,0)        NOT NULL,
    ACCESSIBLE_TRANSPORT NUMBER(1,0)        NOT NULL,
    OPERATIONAL_STATUS   VARCHAR2(25 CHAR)  NOT NULL,
    ACTIVE               NUMBER(1,0)        NOT NULL,
    CREATED_AT           TIMESTAMP(6)       NOT NULL,
    UPDATED_AT           TIMESTAMP(6)       NOT NULL,
    VERSION              NUMBER(19,0)       NOT NULL,
    CONSTRAINT PK_RESCUE_UNIT_GS PRIMARY KEY (RESCUE_UNIT_ID),
    CONSTRAINT UK_RESCUE_UNIT_CODE_GS UNIQUE (UNIT_CODE),
    CONSTRAINT CK_RU_CAPACITY_GS CHECK (CAPACITY BETWEEN 1 AND 50),
    CONSTRAINT CK_RU_ACCESS_GS CHECK (ACCESSIBLE_TRANSPORT IN (0, 1)),
    CONSTRAINT CK_RU_ACTIVE_GS CHECK (ACTIVE IN (0, 1)),
    CONSTRAINT CK_RU_STATUS_GS CHECK (OPERATIONAL_STATUS IN ('AVAILABLE', 'BUSY', 'OUT_OF_SERVICE')),
    CONSTRAINT CK_RU_INSTIT_GS CHECK (INSTITUTION_TYPE IN
        ('FIRE_DEPARTMENT', 'EMERGENCY_MEDICAL_SERVICE', 'MILITARY_POLICE', 'CIVIL_DEFENSE'))
);

CREATE INDEX IX_RU_INSTIT_STATUS_GS
    ON TB_STORMAID_RESCUE_UNIT_GS (INSTITUTION_TYPE, OPERATIONAL_STATUS);

CREATE TABLE TB_STORMAID_UNIT_ASSIGNMENT_GS (
    UNIT_ASSIGNMENT_ID   NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    RESCUE_UNIT_ID       NUMBER(19,0)      NOT NULL,
    RESPONDER_USER_ID    NUMBER(19,0)      NOT NULL,
    ASSIGNED_BY_USER_ID  NUMBER(19,0)      NOT NULL,
    STATUS               VARCHAR2(20 CHAR) NOT NULL,
    STARTED_AT           TIMESTAMP(6)      NOT NULL,
    ENDED_AT             TIMESTAMP(6),
    CREATED_AT           TIMESTAMP(6)      NOT NULL,
    VERSION              NUMBER(19,0)      NOT NULL,
    CONSTRAINT PK_UNIT_ASSIGN_GS PRIMARY KEY (UNIT_ASSIGNMENT_ID),
    CONSTRAINT FK_UA_RESCUE_UNIT_GS FOREIGN KEY (RESCUE_UNIT_ID)
        REFERENCES TB_STORMAID_RESCUE_UNIT_GS (RESCUE_UNIT_ID),
    CONSTRAINT CK_UA_STATUS_GS CHECK (STATUS IN ('ACTIVE', 'ENDED'))
);

CREATE INDEX IX_UA_RESPONDER_GS ON TB_STORMAID_UNIT_ASSIGNMENT_GS (RESPONDER_USER_ID);
CREATE INDEX IX_UA_RESCUE_UNIT_GS ON TB_STORMAID_UNIT_ASSIGNMENT_GS (RESCUE_UNIT_ID);
